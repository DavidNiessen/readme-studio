import { assetRepository, type StudioConfig } from "./config";

/** The published action users reference from their profile repository. */
export const ACTION_REPO = "DavidNiessen/readme-generator";
export const ACTION_REF = `${ACTION_REPO}@v1`;
export const STUDIO_URL = "https://davidniessen.github.io/readme-generator/";

export interface WorkflowOptions {
  /** action reference, e.g. DavidNiessen/readme-generator@v1 */
  ref?: string;
  /** include the optional PROFILE_TOKEN secret line */
  profileToken?: boolean;
  configPath?: string;
}

/** Human-readable description of a 5-field cron expression (common shapes only). */
export function describeCron(cron: string): string {
  const [min, hour, dom, mon, dow] = cron.trim().split(/\s+/);
  const pad = (n: string) => n.padStart(2, "0");
  if ([dom, mon, dow].every((x) => x === "*")) {
    if (/^\d+$/.test(min) && /^\d+$/.test(hour)) return `every day at ${pad(hour)}:${pad(min)} UTC`;
    if (/^\d+$/.test(min) && /^\*\/(\d+)$/.test(hour)) return `every ${hour.slice(2)} hours at minute ${min}`;
    if (/^\d+$/.test(min) && hour === "*") return `every hour at minute ${min}`;
  }
  if (dom === "*" && mon === "*" && /^\d$/.test(dow) && /^\d+$/.test(min) && /^\d+$/.test(hour)) {
    const days = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
    return `every ${days[Number(dow) % 7]} at ${pad(hour)}:${pad(min)} UTC`;
  }
  return `on cron "${cron}"`;
}

