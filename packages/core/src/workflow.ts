/** The GitHub Actions workflow that rebuilds the README on a schedule. */
export function workflowYaml(config: StudioConfig, o: WorkflowOptions = {}): string {
  const ref = o.ref ?? ACTION_REF;
  const cfg = o.configPath ?? "readme.config.json";
  return `# Rebuilds the animated profile README ${describeCron(config.output.schedule)}.
# Generated by Readme Studio: ${STUDIO_URL}
name: readme

on:
  schedule:
    - cron: "${config.output.schedule}"
  workflow_dispatch:
  push:
    paths:
      - ${cfg}
      - .github/workflows/readme.yml

permissions:
  contents: write

concurrency:
  group: readme
  cancel-in-progress: true

jobs:
  render:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v4

      - uses: ${ref}
        with:
          config: ${cfg}
          asset-branch: ${config.output.branch}
${
  o.profileToken === false
    ? ""
    : `          # Optional: a fine-grained token with read access to your profile
          # adds private contribution counts and exact totals.
          profile-token: \${{ secrets.PROFILE_TOKEN }}
`
}`;
}

/** SETUP.md shipped in the exported project. */
export function setupGuide(config: StudioConfig): string {
  const repo = assetRepository(config);
  const login = config.profile.login;
  return `# Setting up your animated profile README

This folder was exported from [Readme Studio](${STUDIO_URL}). It contains everything your
profile repository needs:

| File | Purpose |
|---|---|
| \`readme.config.json\` | Your design: theme, layout and widget options. Re-import it in the studio any time. |
| \`.github/workflows/readme.yml\` | Rebuilds every image ${describeCron(config.output.schedule)} and on every config change. |
| \`README.md\` | The generated layout. It only contains \`<picture>\` tags pointing at the \`${config.output.branch}\` branch. |

## 1. Create your profile repository

GitHub shows the README of the repository named exactly like your username on your profile:
**[github.com/${login}/${login}](https://github.com/${login}/${login})**. Create it (public) if it doesn't exist yet.

## 2. Add the files

Copy the three files into the repository root (keep the \`.github/workflows\` folder structure) and push:

\`\`\`bash
git add readme.config.json README.md .github/workflows/readme.yml
git commit -m "feat: animated profile readme"
git push
\`\`\`

## 3. Allow the workflow to push

In **Settings → Actions → General → Workflow permissions**, select **Read and write permissions**.
The workflow pushes the rendered images to the \`${config.output.branch}\` branch and updates \`README.md\` when the layout changes.

## 4. Run it once

Open the **Actions** tab, pick **readme** and click **Run workflow**. After about a minute your
profile shows the animated README. From now on it rebuilds itself ${describeCron(config.output.schedule)}.

## Optional: exact numbers and private contributions

The default \`GITHUB_TOKEN\` can read your public data. For private contribution counts, create a
[fine-grained personal access token](https://github.com/settings/personal-access-tokens/new)
with read-only access to your account, save it as a repository secret named \`PROFILE_TOKEN\` and keep the
\`profile-token\` line in the workflow.

## Changing the design

Open the studio, use **Import** with your \`readme.config.json\`, edit, export again and replace the file.
The next run picks up the change automatically.

Assets are served from \`https://raw.githubusercontent.com/${repo}/${config.output.branch}/\`.
`;
}
