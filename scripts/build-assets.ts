const bySlug = new Map<string, { title: string; hex: string; path: string }>();
for (const k of Object.keys(simpleIcons)) {
  const i = simpleIcons[k];
  if (i && i.slug) bySlug.set(i.slug, i);
}

/** Renamed ids: keep friendlier names for the UI. */
const ALIAS: Record<string, string> = { amazonwebservices: "aws", nodedotjs: "nodejs", vuedotjs: "vue", nextdotjs: "nextjs", threedotjs: "threejs", devdotto: "devto", openjdk: "openjdk", junit5: "junit" };

interface IconRec {
  t: string;
  c: string;
  v: string;
  b: string;
  src: "si" | "fa" | "st" | "rs";
}
const icons: Record<string, IconRec> = {};

for (const slug of ICON_SLUGS) {
  const i = bySlug.get(slug);
  if (!i) throw new Error(`simple-icons is missing ${slug}`);
  icons[ALIAS[slug] ?? slug] = { t: i.title, c: `#${i.hex}`, v: "0 0 24 24", b: `<path fill="currentColor" d="${i.path}"/>`, src: "si" };
}

// vendored extras that simple-icons no longer ships
const extraDir = join(core, "assets/icons");
const extraMeta: Record<string, [string, IconRec["src"]]> = {
  java: ["Java", "fa"],
  aws: ["AWS", "fa"],
  linkedin: ["LinkedIn", "fa"],
  playwright: ["Playwright", "st"],
};
for (const f of readdirSync(extraDir).filter((f) => f.endsWith(".svg"))) {
  const id = f.replace(/\.svg$/, "");
  const raw = readFileSync(join(extraDir, f), "utf8").trim();
  const head = /^<svg([^>]*)>/.exec(raw)?.[1] ?? "";
  const v = /viewBox="([^"]+)"/.exec(head)?.[1] ?? "0 0 24 24";
  const fill = /fill="([^"]+)"/.exec(head)?.[1] ?? "none";
  let b = raw.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  if (fill !== "none") b = b.replace(/<path /g, '<path fill="currentColor" ');
  const [t, src] = extraMeta[id] ?? [id, "rs"];
  icons[id] = { t, c: fill === "none" ? "multi" : fill, v, b, src };
}

