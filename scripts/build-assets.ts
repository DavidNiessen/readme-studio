/**
 * Vendors fonts and brand icons into packages/core and generates the
 * TypeScript data modules the isomorphic renderer imports.
 *
 *   npx tsx scripts/build-assets.ts
 *
 * Outputs (all committed):
 *   packages/core/assets/fonts/<id>-<weight>.{woff,woff2}   vendored font files
 *   packages/core/src/fonts/data/<id>.ts                    base64 woff2 per weight (lazy-loadable)
 *   packages/core/src/fonts/metrics.ts                      advance widths for text measurement
 *   packages/core/src/icons/data.ts                         brand icon bodies
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
// eslint-disable-next-line @typescript-eslint/no-require-imports
const opentype = require("opentype.js");
// eslint-disable-next-line @typescript-eslint/no-require-imports
const simpleIcons = require("simple-icons");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const core = join(root, "packages/core");
const fontOut = join(core, "assets/fonts");
const fontData = join(core, "src/fonts/data");
mkdirSync(fontOut, { recursive: true });
mkdirSync(fontData, { recursive: true });

/** id → fontsource package name, display name, category */
export const FONTS = [
  ["jetbrains-mono", "JetBrains Mono", "mono"],
  ["ibm-plex-mono", "IBM Plex Mono", "mono"],
  ["fira-code", "Fira Code", "mono"],
  ["geist-mono", "Geist Mono", "mono"],
  ["space-mono", "Space Mono", "mono"],
  ["source-code-pro", "Source Code Pro", "mono"],
  ["inter", "Inter", "sans"],
  ["geist-sans", "Geist", "sans"],
  ["space-grotesk", "Space Grotesk", "sans"],
  ["manrope", "Manrope", "sans"],
  ["fraunces", "Fraunces", "serif"],
  ["ibm-plex-serif", "IBM Plex Serif", "serif"],
] as const;

const WEIGHTS = [400, 700] as const;
const FIRST = 32;
const LAST = 255;

const metrics: Record<string, Record<number, { upm: number; asc: number; desc: number; w: number[] }>> = {};

for (const [id] of FONTS) {
  const pkg = join(root, "node_modules/@fontsource", id, "files");
  const b64: Record<number, string> = {};
  metrics[id] = {};
  for (const w of WEIGHTS) {
    const base = `${id}-latin-${w}-normal`;
    copyFileSync(join(pkg, `${base}.woff`), join(fontOut, `${id}-${w}.woff`));
    copyFileSync(join(pkg, `${base}.woff2`), join(fontOut, `${id}-${w}.woff2`));
    b64[w] = readFileSync(join(pkg, `${base}.woff2`)).toString("base64");
    const buf = readFileSync(join(pkg, `${base}.woff`));
    const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    const upm = font.unitsPerEm;
    const widths: number[] = [];
    for (let c = FIRST; c <= LAST; c++) {
      const g = font.charToGlyph(String.fromCharCode(c));
      // per-mille of the em, enough precision for layout
      widths.push(g && g.index !== 0 ? Math.round((g.advanceWidth / upm) * 1000) : -1);
    }
    const asc = Math.round((font.ascender / upm) * 1000);
    const desc = Math.round((-font.descender / upm) * 1000);
    metrics[id][w] = { upm, asc, desc, w: widths };
  }
  writeFileSync(
    join(fontData, `${id}.ts`),
    `// generated by scripts/build-assets.ts. Do not edit.\n// ${id} latin subset, woff2, SIL Open Font License 1.1\nconst data: Record<400 | 700, string> = {\n${WEIGHTS.map((w) => `  ${w}: "${b64[w]}",`).join("\n")}\n};\nexport default data;\n`,
  );
  console.log(`font ${id}`);
}

const metricLines = Object.entries(metrics)
  .map(
    ([id, ws]) =>
      `  "${id}": {\n${Object.entries(ws)
        .map(([w, m]) => `    ${w}: { asc: ${m.asc}, desc: ${m.desc}, w: [${m.w.join(",")}] },`)
        .join("\n")}\n  },`,
  )
  .join("\n");
writeFileSync(
  join(core, "src/fonts/metrics.ts"),
  `// generated by scripts/build-assets.ts. Do not edit.\n/** Advance widths in 1/1000 em for code points ${FIRST}..${LAST} (-1 = missing glyph). */\nexport interface FontMetrics { asc: number; desc: number; w: number[] }\nexport const METRIC_FIRST = ${FIRST};\nexport const metrics: Record<string, Record<400 | 700, FontMetrics>> = {\n${metricLines}\n};\n`,
);

