const lucideDir = join(root, "node_modules/lucide-react/dist/esm/icons");
const glyphNames = new Set([...readFileSync(join(core, "src/widgets/parts.ts"), "utf8").matchAll(/^  ([a-z]+): `/gm)].map((m) => m[1]));
