  const head = /^<svg([^>]*)>/.exec(raw)?.[1] ?? "";
  const v = /viewBox="([^"]+)"/.exec(head)?.[1] ?? "0 0 24 24";
  const fill = /fill="([^"]+)"/.exec(head)?.[1] ?? "none";
